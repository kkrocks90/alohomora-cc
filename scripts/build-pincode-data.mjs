// Builds worker/pincode-data.js from the open "All India Pincode list with latitude and longitude" CSV (MIT).
// Usage: node scripts/build-pincode-data.mjs <path-to-Minimal-India-Pincode-list-with-latitude-and-longitude.csv>
import { readFileSync, writeFileSync } from "node:fs";

const [source] = process.argv.slice(2);
if (!source) throw new Error("Pass the path to the CSV file.");

const STATE_NAMES = {
  "New Delhi": "Delhi",
  Orisa: "Odisha",
  Chattisgarh: "Chhattisgarh",
  Uttaranchal: "Uttarakhand",
  Pondicherry: "Puducherry",
  "Andaman and Nicobar": "Andaman and Nicobar Islands",
  "Dadar and Nagar Haveli": "Dadra and Nagar Haveli and Daman and Diu",
  "Daman and Diu": "Dadra and Nagar Haveli and Daman and Diu",
};

function modernState(pincode, state) {
  const name = STATE_NAMES[state] ?? state;
  const prefix = Number(pincode.slice(0, 3));
  if (name === "Andhra Pradesh" && prefix >= 500 && prefix <= 509) return "Telangana";
  if (name === "Jammu and Kashmir" && prefix === 194) return "Ladakh";
  return name;
}

const title = (text) => text.toLowerCase().replace(/\b[a-z]/g, (letter) => letter.toUpperCase());
const rows = readFileSync(source, "utf8").split(/\r?\n/).slice(1).filter(Boolean);
const states = [];
const data = {};
for (const row of rows) {
  const [, pincode, area, state, latitude, longitude] = row.split('","').map((cell) => cell.replace(/"/g, ""));
  if (!/^[1-9][0-9]{5}$/.test(pincode) || data[pincode]) continue;
  const lat = Number(latitude);
  const lon = Number(longitude);
  if (!Number.isFinite(lat) || !Number.isFinite(lon) || lat < 6 || lat > 38 || lon < 68 || lon > 98) continue;
  const stateName = modernState(pincode, state);
  if (!states.includes(stateName)) states.push(stateName);
  data[pincode] = [Number(lat.toFixed(4)), Number(lon.toFixed(4)), states.indexOf(stateName), title(area)];
}

const output = `// Generated by scripts/build-pincode-data.mjs from the MIT-licensed
// "All India Pincode list with latitude and longitude" (github.com/mrparveensharma). Do not edit by hand.
// pincode -> [latitude, longitude, index into PINCODE_STATES, area name]
export const PINCODE_STATES = ${JSON.stringify(states)};
export const PINCODE_DATA = ${JSON.stringify(data)};
`;
writeFileSync(new URL("../worker/pincode-data.js", import.meta.url), output);
console.log(`Wrote ${Object.keys(data).length} PIN codes.`);
